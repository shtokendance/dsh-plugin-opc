import { chromium } from 'playwright'
import { readFile, writeFile } from 'node:fs/promises'
const log = await readFile('/tmp/opc-dsh-runtime.log', 'utf8')
const url = log.match(/http:\/\/127\.0\.0\.1:3080\/\?token=[^\s]+/)?.[0]
if (!url) throw new Error('Host URL unavailable')
const browser = await chromium.launch({ headless: false, channel: 'chrome' })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await context.newPage()
await page.goto(url)
await page.waitForTimeout(2000)
const proceed = page.getByRole('button', { name: '继续', exact: true })
if (await proceed.count()) await proceed.click()
await page.getByRole('button', { name: '选择工作区', exact: true }).click()
await page.getByRole('menuitem', { name: 'opc', exact: true }).click()
await page.getByRole('button', { name: '打开右侧边栏', exact: true }).click()
await page.getByRole('button', { name: '企业知识库', exact: true }).click()
await page.getByRole('button', { name: '企业微信 / SSO 登录', exact: true }).click()
const link = page.getByRole('link', { name: '重新打开授权页' })
await link.waitFor()
const authorizeUrl = await link.getAttribute('href')
if (!authorizeUrl || new URL(authorizeUrl).origin !== 'https://shtokendance.benlai.com') throw new Error('Unexpected authorization origin')
const authorization = await context.newPage()
await authorization.goto(authorizeUrl)
console.log('Authorization page opened:', await authorization.title())
console.log((await authorization.locator('body').innerText()).slice(0, 1200))
await authorization.screenshot({ path: '.runtime/evidence/login-page.png' })
await page.getByRole('button', { name: '退出登录', exact: true }).waitFor({ timeout: 300_000 })
console.log('Enterprise login completed; resource panel ready.')
await page.bringToFront()
await page.waitForTimeout(1500)
await page.screenshot({ path: '.runtime/evidence/authenticated.png' })
await writeFile('.runtime/evidence/authenticated.txt', await page.locator('body').innerText())
// Keep this user-facing acceptance window available until the user closes it.
await new Promise(resolve => browser.on('disconnected', resolve))
